"""Write docs/MODEL-CARD.md from the committed reports, so every number in it traces to a result file."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from ldp.schema import EXCLUDED_FOR_LEAKAGE, FEATURE_NAMES, PROTECTED, TRACT_DEMOGRAPHICS


def _load(path: Path) -> dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8"))


def _pct(x: float) -> str:
    return f"{100 * x:.1f}%"


def render(reports: Path, model_dir: Path) -> str:
    m = _load(reports / "model-metrics.json")
    fair = _load(reports / "fairness.json")
    psi = _load(reports / "psi.json")
    audit = _load(reports / "leakage-audit.json")
    data = _load(reports / "dataset.json")
    meta = _load(model_dir / "metadata.json")
    tf_test = m["models"]["tensorflow"]["test"]
    splits = {s["split"]: s for s in data["splits"]}

    lines = [
        "# Model card: mortgage application referral model",
        "",
        "Generated by `ldp model-card` from `reports/*.json` and `models/ldp/<version>/metadata.json`.",
        "",
        "## Status",
        "",
        (
            f"**Not approved for production.** The fair-lending audit flags {len(fair['flags'])} group(s): "
            + ", ".join(f"`{f}`" for f in fair["flags"])
            + ". Where the model's adverse impact ratio is below the lenders' own, it would widen an existing gap. "
            "See the audit table and `reports/fairness-drivers.json`; a less discriminatory alternative has to pass "
            "the same audit before any use." + _lda_status(reports)
        )
        if fair["flags"]
        else "Passes the fair-lending audit at the operating threshold.",
        "",
        "## Model details",
        "",
        f"- Name and version: `{meta['model_name']}` version {meta['version']}, trained {meta['trained_at']}",
        "- Type: TensorFlow/Keras multilayer perceptron with in-graph preprocessing (imputation, transforms, "
        "standardisation, missing flags, embeddings), Platt-calibrated on the validation year",
        "- Served by TF Serving with two signatures: `serving_default` (probability) and `explain` "
        "(integrated-gradient attributions used for adverse-action reasons)",
        f"- Gold Delta table version used for training: {meta['gold_delta_version']}",
        "",
        "## Intended use",
        "",
        "Decision support for mortgage underwriting: estimate how likely a lender would be to deny an application "
        "and **refer** high-likelihood applications to an underwriter with the main reasons. "
        f"Operating rule: {meta['threshold_rule']} (threshold {meta['threshold']:.4f}).",
        "",
        "Not intended to deny credit automatically, to price loans, or to predict repayment: the label is the "
        "lender's decision, not loan performance.",
        "",
        "## Data",
        "",
        "Public HMDA loan application register (CFPB/FFIEC national snapshot files, public domain). Population: "
        "closed-end, first-lien, 1-4 unit, non-business home purchase and refinance applications that reached a "
        "decision (originated, approved but not accepted, denied). Label: denied.",
        "",
        "| Split | Year | Applications | Denial rate |",
        "|---|---|---|---|",
        *[f"| {k} | {v['year']} | {v['rows']:,} | {_pct(v['denial_rate'])} |" for k, v in splits.items()],
        "",
        f"Inputs ({len(FEATURE_NAMES)}): {', '.join(f'`{n}`' for n in FEATURE_NAMES)}; derived in the graph: "
        "`loan_to_value`, `loan_to_income`.",
        "",
        f"Excluded after the leakage audit (2023, {audit['rows']:,} sampled applications): "
        + ", ".join(f"`{n}`" for n in EXCLUDED_FOR_LEAKAGE)
        + "; post-decision fields (interest rate, fees, purchaser, HOEPA status, denial reasons) are never inputs. "
        f"Protected attributes ({', '.join(PROTECTED)}) and tract demographics ({len(TRACT_DEMOGRAPHICS)} fields) "
        "are used only for the fairness audit.",
        "",
        "## Performance on the 2025 hold-out",
        "",
        "| Model | AUC (95% CI) | KS | Brier | ECE | Referral rate | Denials caught | Precision |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for name, label in (
        ("tensorflow", "TensorFlow MLP (this model)"),
        ("xgboost", "XGBoost baseline"),
        ("logistic_regression", "Logistic regression baseline"),
    ):
        if name not in m["models"]:
            continue
        t = m["models"][name]["test"]
        ci = t.get("auc_ci95", [float("nan"), float("nan")])
        op = t["operating_point"]
        lines.append(
            f"| {label} | {t['auc']:.4f} ({ci[0]:.4f}-{ci[1]:.4f}) | {t['ks']:.3f} | {t['brier']:.4f} | "
            f"{t['ece']:.4f} | {_pct(op['referral_rate'])} | {_pct(op['recall_of_denials'])} | "
            f"{_pct(op['precision'])} |"
        )
    lines += [
        "",
        f"Calibration: ECE {m['models']['tensorflow']['test_uncalibrated_ece']:.4f} before Platt scaling, "
        f"{tf_test['ece']:.4f} after (calibration fitted on 2024, measured on 2025).",
        "",
        "## Fair-lending audit (2025 hold-out, operating threshold)",
        "",
        "Adverse impact ratio (AIR) = favourable rate of the group / favourable rate of the reference group. "
        "Favourable = not referred (model) or approved (lenders' actual decisions). Below 0.80 is flagged; so "
        "is a model AIR more than 0.02 below the lenders' own.",
        "",
        "| Dimension | Group (reference) | Applications | Lenders' AIR | Model AIR | Group AUC |",
        "|---|---|---|---|---|---|",
    ]
    for dim, block in fair["dimensions"].items():
        ref = block["reference"]["group"]
        for g in block["groups"]:
            if "model_air" not in g:
                continue
            lines.append(
                f"| {dim} | {g['group']} ({ref}) | {g['n']:,} | {g['observed_air']:.3f} | "
                f"{g['model_air']:.3f} | {g.get('auc', float('nan')):.3f} |"
            )
    lines += ["", f"Flags: {', '.join(fair['flags']) if fair['flags'] else 'none'}.", ""]
    lines += _drivers_section(reports)
    lines += _lda_section(reports)
    agree = m["reason_agreement"]
    lines += [
        "## Explanations",
        "",
        f"On {agree['applications']:,} denied 2025 applications where the lender's first reported reason was "
        "debt-to-income or collateral, that reason was the model's top reason for "
        f"{_pct(agree['lender_reason_is_top_model_reason'])} and among its top four for "
        f"{_pct(agree['lender_reason_in_model_top_4'])}.",
        "",
        "## Stability",
        "",
        f"Score PSI against the 2023 training population: {psi['score']['valid_2024']:.3f} on 2024, "
        f"{psi['score']['test_2025']:.3f} on 2025. Largest input shifts on 2025: "
        + ", ".join(
            f"`{k}` {v['test_2025']:.3f}"
            for k, v in sorted(psi["features"].items(), key=lambda kv: -kv[1]["test_2025"])[:3]
        )
        + ".",
        "",
        "## Limitations",
        "",
        "- HMDA has no credit score, credit history or employment data. The model sees only loan and income "
        "characteristics, so it cannot weigh what an underwriter weighs most, and its reasons can never cite credit.",
        "- The label is the lenders' decision. The model learns their practices, including any disparities in "
        "them; the fairness audit compares the model with those decisions but cannot make the labels fair.",
        "- HMDA rounds loan amounts and property values to $10,000 midpoints and bins debt-to-income ratios.",
        "- Applications are not individual consumers' credit files; protected attributes are applicant-reported "
        "(or observed) HMDA fields, used only for monitoring.",
        "- A threshold that catches 80% of denials is a policy choice; the referral volume it implies has to fit "
        "underwriting capacity.",
    ]
    return "\n".join(lines) + "\n"


def _drivers_section(reports: Path) -> list[str]:
    """Why the audit fails (integrated-gradient gaps) and what removing one input at a time does to it."""
    lines: list[str] = []
    drivers_path, ablation_path = reports / "fairness-drivers.json", reports / "ablation.json"
    if drivers_path.exists():
        d = _load(drivers_path)
        lines += [
            "### Where the gaps come from",
            "",
            "Mean integrated-gradient attribution of each input, group minus reference (20,000 applications per "
            "side, 2025). The differences add up to the gap in mean logit.",
            "",
            "| Comparison | Gap in mean logit | Largest contributors |",
            "|---|---|---|",
        ]
        for c in d["comparisons"]:
            top = ", ".join(f"`{x['input']}` {x['gap']:+.2f}" for x in c["drivers"][:4])
            label = "Age 62+ vs under 62" if c["dimension"] == "age" else f"{c['group']} vs {c['reference']}"
            lines.append(f"| {label} | {c['mean_logit_gap']:+.2f} | {top} |")
        age = next((c for c in d["comparisons"] if c["dimension"] == "age"), None)
        if age:
            g, r = age["group_profile"], age["reference_profile"]
            lines += [
                "",
                f"The largest contributor for age is `loan_purpose`: applicants 62 and over apply for refinancing far "
                f"more often ({_pct(g['share_refinance'])} vs {_pct(r['share_refinance'])}) and report less income "
                f"(median ${g['median_income_k']:.0f}k vs ${r['median_income_k']:.0f}k).",
            ]
        lines.append("")
    if ablation_path.exists():
        a = _load(ablation_path)
        obs = a["lenders_observed"]
        lines += [
            "### Less discriminatory alternative search (drop one input, XGBoost, same operating rule)",
            "",
            f"Lenders' own AIR on the same 2025 sample: age {obs['air age 62+ vs under 62']:.3f}, Black "
            f"{obs['air Black vs White']:.3f}, female {obs['air Female vs Male']:.3f}. All inputs: AUC "
            f"{a['all_inputs']['test_auc']:.4f}, age AIR {a['all_inputs']['air age 62+ vs under 62']:.3f}, Black AIR "
            f"{a['all_inputs']['air Black vs White']:.3f}.",
            "",
            "| Input removed | AUC | Age AIR | Black AIR | Female AIR |",
            "|---|---|---|---|---|",
        ]
        for r in a["ablations"]:
            lines.append(
                f"| {r['dropped']} | {r['test_auc']:.4f} | {r['air age 62+ vs under 62']:.3f} | "
                f"{r['air Black vs White']:.3f} | {r['air Female vs Male']:.3f} |"
            )
        lines += [
            "",
            "No single removal brings every group to the lenders' level: removing `loan_purpose` lifts the age AIR "
            "to about 0.80 but lowers the Black AIR, and no input is a hidden leak (the largest AUC loss is "
            "debt-to-income). A real alternative needs a joint search (constraints or reweighting), not a "
            "feature list; FinRegLab reports the same about feature removal.",
            "",
        ]
    return lines


LDA_COLUMNS = (
    ("age:Yes", "Age 62+"),
    ("race:Black or African American", "Black"),
    ("race:American Indian or Alaska Native", "Am. Indian"),
    ("race:Native Hawaiian or Other Pacific Islander", "Pac. Islander"),
    ("sex:Female", "Female"),
)


def _airs(summary: dict[str, Any], key: str = "model_air") -> dict[str, float]:
    return {f"{g['dimension']}:{g['group']}": g[key] for g in summary["groups"]}


def _lda_status(reports: Path) -> str:
    """One sentence for the status line: what the joint search (issue #27) found, if it has run."""
    path = reports / "lda-search.json"
    if not path.exists():
        return ""
    r = _load(path)
    h = r.get("holdout_2025")
    if not h:
        return (
            f" The joint search for one (issue #27) has chosen `{r['chosen']['name']}` on 2024; 2025 is not scored yet."
        )
    if h["passes_audit"]:
        return (
            f" The joint search (issue #27) found one: `{h['variant']}` passes the audit on 2025 at AUC "
            f"{h['auc']:.4f} (v1 {h['v1']['auc']:.4f}). It is not exported or served yet."
        )
    chosen = (
        f"`{h['variant']}` passed on 2024 but"
        if r["chosen"]["passes_2024_audit"]
        else f"the closest on 2024, `{h['variant']}`, still"
    )
    return (
        f" The joint search for one (issue #27) found none that passes on 2025: {chosen} flags "
        f"{len(h['flags'])} group(s) there (" + ", ".join(f"`{f}`" for f in h["flags"]) + f") at AUC {h['auc']:.4f} "
        f"(v1 {h['v1']['auc']:.4f}), while passing {len([f for f in h['v1']['flags'] if f not in h['flags']])} of "
        f"v1's {len(h['v1']['flags'])} flagged groups."
    )


def _lda_section(reports: Path) -> list[str]:
    """The joint search of issue #27 (`scripts/lda_search.py`): every variant on 2024, the chosen one on 2025."""
    path = reports / "lda-search.json"
    if not path.exists():
        return []
    r = _load(path)
    ref = r["reference"]["valid_2024"]
    observed = _airs(ref, "observed_air")
    head = " | ".join(label for _, label in LDA_COLUMNS)
    lines = [
        "### Less discriminatory alternative search, joint (2024 validation year)",
        "",
        "Each variant is the v1 recipe with one change to the training loss; protected attributes enter only the "
        "loss, never the inputs or the threshold (ADR 0010). Three variants:",
        "",
        "- **Reweighing** (Kamiran & Calders 2012): each application weighted so that the denial rate is the same "
        "in every age x race x sex cell.",
        "- **Mean-logit penalty**: cross-entropy + lambda x the squared gap in mean logit between each group and its "
        "reference, among approved and among denied applications separately (a relaxation of equalized odds, "
        "Hardt et al. 2016), for age 62+, Black and female applicants. lambda = 0 is the v1 recipe re-run.",
        "- **Referral-rate penalty**: the same, on a smooth referral rate at each batch's own 80%-recall threshold, "
        "with American Indian applicants added (split-halves estimate for small groups). Equal referral rates "
        "among approved and among denied applications would give every group whose denial rate is higher an AIR at "
        "least the lenders' own.",
        "",
        f"Choice, on 2024 only: {r['protocol']['selection'].split('; ', 1)[1]}. AIR of each group v1 fails:",
        "",
        f"| Variant | AUC | Referral rate | {head} | Flags |",
        "|---|---|---|" + "---|" * len(LDA_COLUMNS) + "---|",
        "| Lenders' own decisions | | | " + " | ".join(f"{observed[k]:.3f}" for k, _ in LDA_COLUMNS) + " | |",
    ]
    for c in [r["reference"], *r["candidates"]]:
        v = c["valid_2024"]
        airs = _airs(v)
        lines.append(
            f"| {c['name']} | {v['auc']:.4f} | {_pct(v['referral_rate'])} | "
            + " | ".join(f"{airs[k]:.3f}" for k, _ in LDA_COLUMNS)
            + f" | {len(v['flags'])} |"
        )
    lines += [
        "",
        "A single cut-off is the only threshold ADR 0006 allows. Moving it for everyone changes how many denials "
        "are caught, not just the AIRs (v1, 2024):",
        "",
        "| Denials caught (target) | Referral rate | " + head + " | Flags |",
        "|---|---|" + "---|" * len(LDA_COLUMNS) + "---|",
    ]
    for s in r["operating_rule_sensitivity_v1"]:
        lines.append(
            f"| {_pct(s['recall_target'])} | {_pct(s['referral_rate'])} | "
            + " | ".join(f"{s['model_air'][k]:.3f}" for k, _ in LDA_COLUMNS)
            + f" | {len(s['flags'])} |"
        )
    chosen = r["chosen"]
    lines += [
        "",
        f"Chosen on 2024: **{chosen['name']}** ({chosen['rule']}).",
        "",
    ]
    h = r.get("holdout_2025")
    if not h:
        return [*lines, "The chosen variant has not been scored on 2025 yet.", ""]
    v1 = h["v1"]
    v1_air, lda_air, obs = _airs(v1), _airs(h), _airs(h, "observed_air")
    lines += [
        f"#### The chosen variant on the 2025 hold-out (scored once, {h['scored_at'][:10]})",
        "",
        f"AUC {h['auc']:.4f} ({h['auc_ci95'][0]:.4f}-{h['auc_ci95'][1]:.4f}) against v1's {v1['auc']:.4f}; "
        f"referral rate {_pct(h['referral_rate'])} (v1 {_pct(v1['referral_rate'])}) for "
        f"{_pct(h['recall_of_denials'])} of denials caught. "
        + (
            "**It passes the audit: no group is flagged.**"
            if h["passes_audit"]
            else f"**It does not pass the audit**: {len(h['flags'])} group(s) flagged ("
            + ", ".join(f"`{f}`" for f in h["flags"])
            + ")."
        ),
        "",
        "| Dimension | Group (reference) | Lenders' AIR | v1 AIR | Chosen variant AIR |",
        "|---|---|---|---|---|",
    ]
    for g in h["groups"]:
        k = f"{g['dimension']}:{g['group']}"
        lines.append(
            f"| {g['dimension']} | {g['group']} ({g['reference']}) | {obs[k]:.3f} | {v1_air[k]:.3f} | "
            f"{lda_air[k]:.3f} |"
        )
    fixed = [f for f in v1["flags"] if f not in h["flags"]]
    lines += ["", f"Of the {len(v1['flags'])} groups v1 fails, the chosen variant passes {len(fixed)}."]
    for f in h["flags"]:
        if lda_air[f] >= 1.0:
            lines[-1] += (
                f" `{f}` is flagged at an AIR of {lda_air[f]:.3f}, at or above parity with its reference: the audit "
                f"flags any model AIR more than 0.02 below the lenders' own ({obs[f]:.3f}). Equalized odds moves a "
                "group whose denial rate is lower than its reference's toward parity (the inequality in "
                "`ldp.training.lda` reverses for it), so for such groups this rule and this method pull against each "
                "other. Whether the rule should apply to a group at or above parity is for the audit's owner to "
                "decide; it is not changed here after seeing the 2025 result."
            )
    return [*lines, ""]


def write(reports: Path, model_dir: Path, out: Path) -> None:
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render(reports, model_dir), encoding="utf-8")
